// Create an Array of 8 Integers and Traversal
#include <iostream>
using namespace std;

int main() {
    int arr[8] = {10, 20, 30, 40, 50, 60, 70, 80};
    int size = 8;
    cout << "Array elements: ";
    for (int i = 0; i < size; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;

    return 0;
}